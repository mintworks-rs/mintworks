//! Upgrades for databases already carrying an earlier [`crate::schema`]. One `if from < N` block
//! per version. Adding a change is three edits, all required: the DDL in `schema.rs`'s `create`,
//! the `if from < N { … }` block here, and [`crate::schema::VERSION`] bumped to N.
//!
//! The runner stamps `schema_version` once, after `upgrade` returns, so no block sets a version.

use sqlx::PgConnection;

use mintworks_core::error::ClResult;

use crate::util::DbExt;

/// Version 1 is the first PostgreSQL schema.
pub(crate) async fn upgrade(conn: &mut PgConnection, from: i64) -> ClResult<()> {
	// mintworks-auth: app-declared membership roles (`app.member_role`).
	if from < 2 {
		sqlx::raw_sql("ALTER TABLE memberships ADD COLUMN app_role TEXT;")
			.execute(&mut *conn)
			.await
			.db()?;
	}
	// Scoped settings: existing rows are global, so the new columns default them to (0, 0).
	if from < 3 {
		sqlx::raw_sql(
			"ALTER TABLE settings ADD COLUMN org_id BIGINT NOT NULL DEFAULT 0,
				ADD COLUMN account_id BIGINT NOT NULL DEFAULT 0;
			 ALTER TABLE settings DROP CONSTRAINT settings_pkey;
			 ALTER TABLE settings ADD PRIMARY KEY (org_id, account_id, key);",
		)
		.execute(&mut *conn)
		.await
		.db()?;
	}
	// mintworks-auth: the public account handle.
	if from < 4 {
		sqlx::raw_sql(
			"ALTER TABLE accounts ADD COLUMN handle TEXT;
			 CREATE UNIQUE INDEX idx_account_handle ON accounts(lower(handle))
				WHERE handle IS NOT NULL;",
		)
		.execute(&mut *conn)
		.await
		.db()?;
	}
	// mintworks-auth: app-declared consent kinds. The names are PostgreSQL's for a column CHECK.
	if from < 5 {
		sqlx::raw_sql(
			"ALTER TABLE legal_docs DROP CONSTRAINT IF EXISTS legal_docs_kind_check;
			 ALTER TABLE consents DROP CONSTRAINT IF EXISTS consents_kind_check;",
		)
		.execute(&mut *conn)
		.await
		.db()?;
	}
	// mintworks-core: content-addressed blobs and their holders.
	if from < 6 {
		sqlx::raw_sql(
			"CREATE TABLE blobs (
				id		BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
				uid		TEXT NOT NULL UNIQUE,			-- 'blb_<ULID>'
				org_id		BIGINT NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
				sha256		TEXT NOT NULL,			-- also its location under blobs/
				mime		TEXT NOT NULL,
				size		BIGINT NOT NULL,
				name		TEXT,
				created_by	BIGINT REFERENCES accounts(id) ON DELETE SET NULL,
				created_at	BIGINT NOT NULL,
				unref_at	BIGINT				-- NULL while a blob_refs row holds it
			 );

			 CREATE INDEX idx_blobs_sha ON blobs(sha256);
			 CREATE INDEX idx_blobs_unref ON blobs(unref_at) WHERE unref_at IS NOT NULL;

			 CREATE TABLE blob_refs (
				blob_id		BIGINT NOT NULL REFERENCES blobs(id) ON DELETE CASCADE,
				ref		TEXT NOT NULL,
				created_at	BIGINT NOT NULL,
				claimed_by	BIGINT REFERENCES accounts(id) ON DELETE SET NULL,
				PRIMARY KEY (blob_id, ref)
			 );",
		)
		.execute(&mut *conn)
		.await
		.db()?;
	}
	// mintworks-llm: `kind = 'api'`, and the subject index moves to `(subject, at)`.
	if from < 7 {
		sqlx::raw_sql(
			"ALTER TABLE llm_usage DROP CONSTRAINT IF EXISTS llm_usage_kind_check;
			 ALTER TABLE llm_usage ADD CONSTRAINT llm_usage_kind_check
				CHECK (kind IN ('llm','search','fetch','api'));
			 DROP INDEX IF EXISTS idx_llm_usage_subject;
			 CREATE INDEX idx_llm_usage_subject ON llm_usage(subject, at) WHERE subject IS NOT NULL;",
		)
		.execute(&mut *conn)
		.await
		.db()?;
	}
	// mintworks-llm: rolling per-subject budget windows.
	if from < 8 {
		sqlx::raw_sql(
			"CREATE TABLE llm_budget_windows (
				subject		TEXT NOT NULL,
				window_secs	BIGINT NOT NULL CHECK (window_secs > 0),
				cap_micro_eur	BIGINT NOT NULL CHECK (cap_micro_eur >= 0),
				updated_at	BIGINT NOT NULL,
				PRIMARY KEY (subject, window_secs)
			 );",
		)
		.execute(&mut *conn)
		.await
		.db()?;
	}
	// mintworks-entitle: seat assignments.
	if from < 9 {
		sqlx::raw_sql(
			"CREATE TABLE seat_assignments (
					id		BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
					org_id		BIGINT NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
					key		TEXT NOT NULL,				-- a declared `Limit` entitlement
					account_id	BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
					assigned_at	BIGINT NOT NULL,
					released_at	BIGINT					-- NULL = active; erase releases, never deletes
				);

				CREATE UNIQUE INDEX idx_seat_active ON seat_assignments(org_id, key, account_id)
					WHERE released_at IS NULL;
				CREATE INDEX idx_seat_account ON seat_assignments(account_id) WHERE released_at IS NULL;",
		)
		.execute(&mut *conn)
		.await
		.db()?;
	}
	// mintworks-auth: account-level app roles.
	if from < 10 {
		sqlx::raw_sql(
			"CREATE TABLE account_roles (
					account_id	BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
					role		TEXT NOT NULL,				-- an `app.account_role` name; no rank
					granted_by	TEXT,					-- the granting account's uid; NULL = System
					created_at	BIGINT NOT NULL,
					PRIMARY KEY (account_id, role)
				);

				CREATE INDEX idx_account_roles_role ON account_roles(role);",
		)
		.execute(&mut *conn)
		.await
		.db()?;
	}
	// mintworks-invoice: numbering series per seller, test mode, partner document language and
	// the seller-version branding columns. Every invoice's series is seeded, not just the
	// default: a storno reuses its original's, and allocation refuses a code `seller_series` lacks.
	if from < 11 {
		sqlx::raw_sql(
			"CREATE TABLE seller_series (
					seller_id	BIGINT NOT NULL REFERENCES sellers(id),
					code		TEXT NOT NULL,
					logo_blob	TEXT,				-- a blobs.uid
					is_default	BIGINT NOT NULL DEFAULT 0 CHECK (is_default IN (0,1)),
					created_at	BIGINT NOT NULL,
					PRIMARY KEY (seller_id, code)
				);

				CREATE UNIQUE INDEX idx_seller_series_default ON seller_series(seller_id)
					WHERE is_default = 1;

				INSERT INTO seller_series (seller_id, code, is_default, created_at)
					SELECT id, series_code, 1, created_at FROM sellers;
				INSERT INTO seller_series (seller_id, code, is_default, created_at)
					SELECT DISTINCT i.seller_id, i.series_code, 0, s.created_at
					  FROM invoices i JOIN sellers s ON s.id = i.seller_id
					 WHERE i.series_code IS NOT NULL
					ON CONFLICT DO NOTHING;

				ALTER TABLE sellers ADD COLUMN test_mode BIGINT NOT NULL DEFAULT 0
					CHECK (test_mode IN (0,1));
				ALTER TABLE invoices ADD COLUMN test_mode BIGINT NOT NULL DEFAULT 0
					CHECK (test_mode IN (0,1));
				ALTER TABLE invoices ADD COLUMN doc_lang TEXT
					CHECK (doc_lang IN ('hu','en','hu-en'));
				ALTER TABLE billing_parties ADD COLUMN doc_lang TEXT
					CHECK (doc_lang IN ('hu','en','hu-en'));
				ALTER TABLE seller_versions ADD COLUMN email TEXT;
				ALTER TABLE seller_versions ADD COLUMN accent TEXT;
				ALTER TABLE seller_versions ADD COLUMN logo_blob TEXT;",
		)
		.execute(&mut *conn)
		.await
		.db()?;
	}
	if from < 12 {
		sqlx::raw_sql(
			"ALTER TABLE seller_versions ADD COLUMN cash_accounting BIGINT NOT NULL DEFAULT 0
				CHECK (cash_accounting IN (0,1));",
		)
		.execute(&mut *conn)
		.await
		.db()?;
	}
	if from < 14 {
		sqlx::raw_sql(
			"ALTER TABLE billing_parties ADD COLUMN emails TEXT NOT NULL DEFAULT '[]';
			ALTER TABLE billing_parties ADD COLUMN currency TEXT REFERENCES currencies(code);",
		)
		.execute(&mut *conn)
		.await
		.db()?;
	}
	if from < 15 {
		sqlx::raw_sql(
			"ALTER TABLE services ADD COLUMN name_en TEXT;
			CREATE TABLE service_prices (
				service_id	BIGINT NOT NULL REFERENCES services(id) ON DELETE CASCADE,
				currency	TEXT NOT NULL REFERENCES currencies(code),
				unit_price	BIGINT NOT NULL,
				PRIMARY KEY (service_id, currency)
			);
			INSERT INTO currencies
				(code, price_round_step, cash_round_step, mode, fee_bp, enabled)
				VALUES ('EUR', 1, 1, 'OFFICIAL', 0, 0), ('USD', 1, 1, 'OFFICIAL', 0, 0)
				ON CONFLICT DO NOTHING;",
		)
		.execute(&mut *conn)
		.await
		.db()?;
	}
	// No backfill: conversion stays off for every existing org until it opts in.
	if from < 16 {
		sqlx::raw_sql(
			"CREATE TABLE org_currencies (
				org_id		BIGINT NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
				code		TEXT NOT NULL REFERENCES currencies(code),
				convert		BIGINT NOT NULL DEFAULT 0 CHECK (convert IN (0,1)),
				fee_bp		BIGINT CHECK (fee_bp IS NULL OR fee_bp BETWEEN 0 AND 1000000),
				PRIMARY KEY (org_id, code)
			);",
		)
		.execute(&mut *conn)
		.await
		.db()?;
	}
	// No backfill: a valid row's NULL requester misses `cache_answers` once and refreshes.
	if from < 18 {
		sqlx::raw_sql("ALTER TABLE vies_checks ADD COLUMN requester TEXT;")
			.execute(&mut *conn)
			.await
			.db()?;
	}
	// Not a data migration: filing rows are discarded on purpose, as no deployment holds any.
	// Takes `schema::NAV`, unlike the blocks above, so the two shapes cannot differ.
	if from < 19 {
		sqlx::raw_sql("DROP TABLE nav_submission_xml; DROP TABLE nav_submissions;")
			.execute(&mut *conn)
			.await
			.db()?;
		sqlx::raw_sql(crate::schema::NAV).execute(&mut *conn).await.db()?;
	}
	// Only from the previous version: an older database got these columns from `schema::NAV` above.
	if from == 19 {
		sqlx::raw_sql(
			"ALTER TABLE nav_submissions ADD COLUMN adopt_result TEXT;
			ALTER TABLE nav_submissions ADD COLUMN adopt_detail TEXT;",
		)
		.execute(&mut *conn)
		.await
		.db()?;
	}
	// No backfill: no invoice was mailed by the framework before.
	if from < 21 {
		sqlx::raw_sql(
			"ALTER TABLE invoices ADD COLUMN mail_optout BIGINT NOT NULL DEFAULT 0
				CHECK (mail_optout IN (0,1));
-- One row per attempt to mail an issued invoice or storno to its buyer
-- (`mintworks_invoice::mail`). Its own `INVOICE_MAIL` job is queued in the same transaction.
CREATE TABLE invoice_emails (
	id		BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	uid		TEXT NOT NULL UNIQUE,		-- 'iml_<ULID>'
	org_id		BIGINT NOT NULL,
	invoice_id	BIGINT NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
	kind		TEXT NOT NULL CHECK (kind IN ('INVOICE','STORNO')),
	status		TEXT NOT NULL CHECK (status IN ('QUEUED','SENT','FAILED','NO_EMAIL')),
	recipient	TEXT NOT NULL,			-- the To; '' on NO_EMAIL
	cc		TEXT NOT NULL DEFAULT '[]',	-- JSON array of the Cc addresses, as queued
	reason		TEXT CHECK (reason IN ('DAILY_LIMIT','PDF_TIMEOUT','SEND_FAILED')),
	at		BIGINT NOT NULL,		-- queued
	manual		BIGINT NOT NULL CHECK (manual IN (0,1))
);

CREATE INDEX idx_invoice_emails_invoice ON invoice_emails(org_id, invoice_id);
CREATE INDEX idx_invoice_emails_queued ON invoice_emails(at) WHERE status = 'QUEUED';
CREATE INDEX idx_invoice_emails_at ON invoice_emails(at);
",
		)
		.execute(&mut *conn)
		.await
		.db()?;
	}
	Ok(())
}

